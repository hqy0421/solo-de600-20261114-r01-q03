"""Core data types for the CEP engine."""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Mapping, Optional


@dataclass(frozen=True)
class Event:
    """A single behavioural event tagged with event-time metadata.

    Parameters
    ----------
    event_type:
        Logical event type, e.g. ``"search"``, ``"view"``, ``"consult"``.
    timestamp:
        Event time in seconds (or any consistent numeric time unit). All
        window/watermark logic works in event time, never wall-clock time.
    key:
        Partition key, typically the user or session id. Matching state is
        kept independently per key.
    event_id:
        Unique identifier of the event. Used for event-reuse bookkeeping and
        for stable output. If ``None`` it is generated by the engine from the
        per-key arrival order.
    data:
        Arbitrary event payload; predicates in the pattern receive the whole
        :class:`Event` so they may inspect ``data``.
    """

    event_type: Any
    timestamp: float
    key: Any = None
    event_id: Any = None
    data: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        # dataclass(frozen=True) still allows object.__setattr__ once.
        if not isinstance(self.data, Mapping):
            raise TypeError("event data must be a mapping")

    @classmethod
    def from_mapping(
        cls,
        raw: Mapping[str, Any],
        *,
        key: Any = None,
        type_field: str = "event_type",
        timestamp_field: str = "timestamp",
        id_field: Optional[str] = "event_id",
        key_field: Optional[str] = None,
    ) -> "Event":
        """Build an :class:`Event` from a plain dict.

        Fields not consumed by the type/timestamp/id/key mapping are kept in
        ``data``.
        """
        consumed = {type_field, timestamp_field}
        if id_field:
            consumed.add(id_field)
        if key_field:
            consumed.add(key_field)
        payload = {k: v for k, v in raw.items() if k not in consumed}
        return cls(
            event_type=raw[type_field],
            timestamp=raw[timestamp_field],
            key=raw[key_field] if key_field else key,
            event_id=raw.get(id_field) if id_field else None,
            data=payload,
        )


@dataclass(frozen=True)
class Match:
    """A completed, watermark-stable pattern match.

    Attributes
    ----------
    pattern_name:
        Name of the pattern that matched.
    key:
        Partition key (user/session) the match belongs to.
    events:
        The events participating in the match, ordered by event time (ties
        broken by per-key arrival order). Only positive steps contribute
        events; an absence condition contributes none.
    events_by_step:
        Mapping of step name -> list of events captured by that step.
    started_at / ended_at:
        Event time of the first / last contributing event.
    absence_verified:
        For patterns ending in a timed absence, the timestamp up to which the
        absence has been verified (``watermark`` at decision time). ``None``
        for patterns without an absence step.
    match_id:
        Deterministic identifier, derived from the pattern name, key and the
        ids of the contributing events. Identical input always yields the same
        id.
    """

    pattern_name: str
    key: Any
    events: List[Event]
    events_by_step: Dict[str, List[Event]]
    started_at: float
    ended_at: float
    absence_verified: Optional[float] = None
    match_id: str = ""

    def event_ids(self):
        return [e.event_id for e in self.events]

    def __str__(self):  # pragma: no cover - cosmetic
        ids = [str(e.event_id) for e in self.events]
        tail = (
            f" absence verified to t={self.absence_verified}"
            if self.absence_verified is not None
            else ""
        )
        return (
            f"<Match {self.pattern_name!r} key={self.key!r} "
            f"events={ids}{tail}>"
        )

    __repr__ = __str__
